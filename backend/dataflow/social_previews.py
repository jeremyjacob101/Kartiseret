class SocialPreviewWorker:
    """Synchronous JSON-lines bridge to the existing Node/Sharp card renderer."""

    def __init__(self, process: subprocess.Popen[str]):
        self.process = process

    @classmethod
    def start(cls) -> "SocialPreviewWorker":
        if shutil.which("node") is None:
            raise RuntimeError("Node.js is required to render static social cards")
        version = subprocess.run(
            ["node", "--version"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
            timeout=10,
        ).stdout.strip()
        match = re.match(r"^v(\d+)", version)
        if not match or int(match.group(1)) < 24:
            raise RuntimeError("Static social card generation requires Node.js 24 or later")

        build = subprocess.run(
            ["npm", "run", "server:build"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=180,
        )
        if build.returncode != 0:
            raise RuntimeError("Could not build the shared catalog renderer packages")

        process = subprocess.Popen(
            ["node", "--import", "tsx", str(WORKER_PATH)],
            cwd=ROOT,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
            encoding="utf-8",
            bufsize=1,
            env=os.environ.copy(),
        )
        return cls(process)

    def request(self, message: dict[str, Any]) -> dict[str, Any]:
        if self.process.poll() is not None or not self.process.stdin or not self.process.stdout:
            raise RuntimeError("Static social card worker stopped unexpectedly")
        self.process.stdin.write(json.dumps(message, separators=(",", ":")) + "\n")
        self.process.stdin.flush()
        line = self.process.stdout.readline()
        if not line:
            raise RuntimeError("Static social card worker returned no result")
        result = json.loads(line)
        if not isinstance(result, dict) or result.get("ok") is not True:
            reason = result.get("error") if isinstance(result, dict) else None
            raise RuntimeError(str(reason or "Static social card worker failed"))
        return result

    def close(self) -> None:
        if self.process.stdin and not self.process.stdin.closed:
            self.process.stdin.close()
        try:
            self.process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self.process.terminate()
            try:
                self.process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=3)


def _missing_object(error: Exception) -> bool:
    response = getattr(error, "response", {})
    code = str(response.get("Error", {}).get("Code", ""))
    return code in {"404", "NoSuchKey", "NotFound"}


def _social_object_exists(storage: ArtworkStorage, key: str) -> bool:
    try:
        result = storage.client.head_object(Bucket=storage.bucket, Key=key)
    except Exception as error:
        if _missing_object(error):
            return False
        raise
    return (
        result.get("ContentType") == "image/jpeg"
        and 0 < int(result.get("ContentLength") or 0) <= MAX_CARD_BYTES
    )


def _app_image_source(storage: ArtworkStorage, kind: str, image_url: str) -> bytes:
    parsed = urlsplit(image_url)
    configured_origin = urlsplit(os.environ.get("R2_IMAGE_ORIGIN", "").strip())
    host = (parsed.hostname or "").lower()
    configured_host = (configured_origin.hostname or "").lower()
    local_http = parsed.scheme == "http" and host in {"localhost", "127.0.0.1"}
    match = R2_IMAGE_PATH_RE.fullmatch(parsed.path)
    if (
        (parsed.scheme != "https" and not local_http)
        or not parsed.hostname
        or parsed.username
        or parsed.password
        or parsed.query
        or parsed.fragment
        or host not in {configured_host, "seret.site", "www.seret.site", "localhost", "127.0.0.1"}
        or not match
        or match.group(1) != kind
    ):
        raise ValueError("Catalog artwork URL is not a supported R2 image path")

    digest = match.group(2)
    widths = (780, 342, 185) if kind == "poster" else (1280, 780)
    last_error: Exception | None = None
    for width in widths:
        key = f"artwork/v1/{kind}/{digest}/{width}.webp"
        try:
            result = storage.client.get_object(Bucket=storage.bucket, Key=key)
            body = result["Body"]
            try:
                value = body.read(MAX_SOURCE_BYTES + 1)
            finally:
                body.close()
            if not value or len(value) > MAX_SOURCE_BYTES:
                raise ValueError("R2 artwork source exceeds the byte limit")
            if result.get("ContentType") != "image/webp":
                raise ValueError("R2 artwork source has an unexpected content type")
            return value
        except Exception as error:
            if _missing_object(error):
                last_error = error
                continue
            raise
    raise RuntimeError("No supported R2 source variant exists") from last_error


def _tmdb_image_source(image_url: str, kind: str) -> bytes:
    from backend.dataflow.backfill_catalog_artwork import tmdb_path

    path = tmdb_path(image_url)
    if not path:
        raise ValueError("Catalog artwork URL is not a supported TMDB image path")
    size = "w780" if kind == "poster" else "w1280"
    import requests

    with requests.get(
        f"https://image.tmdb.org/t/p/{size}{path}",
        timeout=(5, 30),
        stream=True,
        allow_redirects=False,
    ) as response:
        if response.status_code != 200:
            raise RuntimeError("TMDB artwork request did not return HTTP 200")
        if not (response.headers.get("Content-Type") or "").lower().startswith("image/"):
            raise ValueError("TMDB returned a non-image response")
        declared = response.headers.get("Content-Length")
        if declared:
            try:
                if int(declared) > MAX_SOURCE_BYTES:
                    raise ValueError("TMDB artwork source exceeds the byte limit")
            except ValueError as error:
                if "byte limit" in str(error):
                    raise
                raise ValueError("TMDB returned an invalid content length") from error
        chunks: list[bytes] = []
        total = 0
        for chunk in response.iter_content(64 * 1024):
            if not chunk:
                continue
            total += len(chunk)
            if total > MAX_SOURCE_BYTES:
                raise ValueError("TMDB artwork source exceeds the byte limit")
            chunks.append(chunk)
        if total == 0:
            raise ValueError("TMDB returned an empty artwork response")
        return b"".join(chunks)


def _read_source_image(storage: ArtworkStorage, image_url: str, kind: str) -> bytes:
    parsed = urlsplit(image_url)
    if parsed.scheme == "https" and parsed.hostname == "image.tmdb.org":
        return _tmdb_image_source(image_url, kind)
    # The catalog uses a backdrop as the poster when no poster is available.
    # Resolve the actual stored artwork kind before selecting its variants.
    match = R2_IMAGE_PATH_RE.fullmatch(parsed.path)
    stored_kind = match.group(1) if match else kind
    return _app_image_source(storage, stored_kind, image_url)


def _card_sources(storage: ArtworkStorage, data: dict[str, Any]) -> tuple[bytes | None, bytes | None]:
    poster_url = data.get("posterUrl") or ""
    backdrop_url = data.get("backdropUrl") or ""
    poster = _read_source_image(storage, poster_url, "poster") if poster_url else None
    if not backdrop_url or backdrop_url == poster_url:
        return poster, poster
    backdrop = _read_source_image(storage, backdrop_url, "backdrop")
    return poster, backdrop


def _verify_current_source(client, worker: SocialPreviewWorker, table: str, primary_key: str, key_value: Any, columns: str, expected_fingerprint: str) -> bool:
    response = (
        client.table(table)
        .select(columns)
        .eq(primary_key, key_value)
        .limit(1)
        .execute()
    )
    current = response.data or []
    if len(current) != 1 or current[0].get("solo_update") is True:
        return False
    result = worker.request(
        {"op": "fingerprint", "table": table, "record": current[0]}
    )
    return result.get("fingerprint") == expected_fingerprint


def refresh_social_previews(
    client,
    storage: ArtworkStorage,
    *,
    dry_run: bool = False,
    limit: int | None = None,
    worker: SocialPreviewWorker | None = None,
    lease_guard=None,
) -> dict[str, int]:
    """Refresh stale/missing cards; resumable because each completed row points to its card."""
    if limit is not None and limit < 1:
        raise ValueError("limit must be a positive integer")
    stats = {"scanned": 0, "updated": 0, "unchanged": 0, "failed": 0, "stale": 0, "pending": 0}
    owns_worker = worker is None
    worker = worker or SocialPreviewWorker.start()
    completed_work = 0
    try:
        for table, primary_key, _coming_soon, columns in TABLES:
            rows = each_row(client, table, columns, lease_guard=lease_guard) if lease_guard else each_row(client, table, columns)
            for row in rows:
                stats["scanned"] += 1
                if row.get("solo_update") is True:
                    stats["unchanged"] += 1
                    continue
                try:
                    hashed = worker.request(
                        {"op": "fingerprint", "table": table, "record": row}
                    )
                    fingerprint = hashed.get("fingerprint")
                    data = hashed.get("data")
                    if not isinstance(fingerprint, str) or not FINGERPRINT_RE.fullmatch(fingerprint) or not isinstance(data, dict):
                        raise RuntimeError("Renderer returned an invalid card fingerprint")

                    key = f"social/v1/{fingerprint}/card.jpg"
                    exists = _social_object_exists(storage, key)
                    if row.get("social_preview_fingerprint") == fingerprint and exists:
                        stats["unchanged"] += 1
                        continue
                    if limit is not None and completed_work >= limit:
                        return stats
                    stats["pending"] += 1
                    if dry_run:
                        completed_work += 1
                        continue

                    if not exists:
                        if lease_guard:
                            lease_guard()
                        poster, backdrop = _card_sources(storage, data)
                        rendered = worker.request(
                            {
                                "op": "render",
                                "data": data,
                                "posterSource": base64.b64encode(poster).decode("ascii") if poster is not None else None,
                                "backdropSource": base64.b64encode(backdrop).decode("ascii") if backdrop is not None else None,
                            }
                        )
                        # The JSON-lines bridge uses base64, not hex. Keep the
                        # encoded fields bounded before passing bytes to Sharp.
                        jpeg_base64 = rendered.get("jpeg")
                        if not isinstance(jpeg_base64, str):
                            raise RuntimeError("Renderer returned malformed image data")
                        try:
                            jpeg = base64.b64decode(jpeg_base64, validate=True)
                        except ValueError as error:
                            raise RuntimeError("Renderer returned malformed image data") from error
                        if not jpeg.startswith(b"\xff\xd8\xff") or len(jpeg) > MAX_CARD_BYTES:
                            raise RuntimeError("Renderer returned an invalid JPEG")
                        if lease_guard:
                            lease_guard()
                        storage.client.put_object(
                            Bucket=storage.bucket,
                            Key=key,
                            Body=jpeg,
                            ContentType="image/jpeg",
                            CacheControl="public, max-age=31536000, immutable",
                        )
                        if not _social_object_exists(storage, key):
                            raise RuntimeError("Uploaded social card did not verify in R2")

                    if not _verify_current_source(
                        client,
                        worker,
                        table,
                        primary_key,
                        row[primary_key],
                        columns,
                        fingerprint,
                    ):
                        stats["stale"] += 1
                        completed_work += 1
                        continue

                    if lease_guard:
                        lease_guard()
                    update = client.table(table).update(
                        {"social_preview_fingerprint": fingerprint}
                    ).eq(primary_key, row[primary_key])
                    previous = row.get("social_preview_fingerprint")
                    if previous is None:
                        update = update.is_("social_preview_fingerprint", "null")
                    else:
                        update = update.eq("social_preview_fingerprint", previous)
                    saved = update.execute().data or []
                    if len(saved) != 1:
                        stats["stale"] += 1
                    else:
                        stats["updated"] += 1
                    completed_work += 1
                except Exception as error:
                    from backend.utils.log.r2_budget import R2BudgetError, R2BudgetExceeded

                    if isinstance(error, (R2BudgetError, R2BudgetExceeded)):
                        raise
                    stats["failed"] += 1
                    completed_work += 1
                    LOGGER.warning(
                        "Social preview refresh failed for %s key=%s (%s)",
                        table,
                        row.get(primary_key),
                        type(error).__name__,
                    )
        return stats
    finally:
        if owns_worker:
            worker.close()


def cleanup_social_previews(
    client,
    storage: ArtworkStorage,
    *,
    apply: bool,
    grace_days: int = 30,
    max_deletes: int = 500,
    lease_guard=None,
) -> dict[str, object]:
    """Delete only old cards whose fingerprint is absent from every catalog table."""
    if grace_days < 0 or max_deletes < 1:
        raise ValueError("Cleanup grace period and deletion bound must be non-negative/positive")
    live: set[str] = set()
    for table, _primary_key, _coming_soon, columns in TABLES:
        rows = each_row(client, table, columns, lease_guard=lease_guard) if lease_guard else each_row(client, table, columns)
        for row in rows:
            fingerprint = row.get("social_preview_fingerprint")
            if fingerprint is None:
                continue
            if not isinstance(fingerprint, str) or not FINGERPRINT_RE.fullmatch(fingerprint):
                raise RuntimeError(f"Social preview reference scan found malformed data in {table}; no deletion was attempted")
            live.add(fingerprint)

    if lease_guard:
        lease_guard()
    cutoff = datetime.now(timezone.utc) - timedelta(days=grace_days)
    eligible = 0
    candidates: list[str] = []
    paginator = storage.client.get_paginator("list_objects_v2")
    for page in paginator.paginate(Bucket=storage.bucket, Prefix="social/v1/"):
        if lease_guard:
            lease_guard()
        contents = page.get("Contents", [])
        if not isinstance(contents, list):
            raise RuntimeError("Social preview R2 listing was malformed; no deletion was attempted")
        for obj in contents:
            if not isinstance(obj, dict):
                raise RuntimeError("Social preview R2 listing was malformed; no deletion was attempted")
            key, modified = obj.get("Key"), obj.get("LastModified")
            if not isinstance(key, str) or not key.startswith("social/v1/") or not isinstance(modified, datetime):
                raise RuntimeError("Social preview R2 listing was incomplete; no deletion was attempted")
            match = SOCIAL_OBJECT_KEY_RE.fullmatch(key)
            if not match:
                raise RuntimeError("Social preview R2 listing contains an unknown object key; no deletion was attempted")
            if modified.tzinfo is None:
                modified = modified.replace(tzinfo=timezone.utc)
            if match.group(1) in live or modified > cutoff:
                continue
            eligible += 1
            if len(candidates) < max_deletes:
                candidates.append(key)

    deleted = 0
    if apply and candidates:
        if lease_guard:
            lease_guard()
        response = storage.client.delete_objects(
            Bucket=storage.bucket,
            Delete={"Objects": [{"Key": key} for key in candidates], "Quiet": True},
        )
        if response.get("Errors"):
            raise RuntimeError("Social preview cleanup did not confirm every deletion")
        deleted = len(candidates)
    return {
        "live_fingerprints": len(live),
        "eligible_objects": eligible,
        "deletion_batch": len(candidates),
        "sample_keys": candidates[:20],
        "deleted": deleted,
    }


def refresh_configured_social_previews() -> dict[str, int] | None:
    """Best-effort after-publication hook; artwork failures never undo a scrape."""
    try:
        storage = ArtworkStorage.from_environment()
        if storage is None:
            LOGGER.info("Skipping social previews: R2 storage is not configured")
            return None
        supabase_url = os.environ.get("SUPABASE_URL", "").strip()
        service_key = os.environ.get("SUPABASE_SERVICE_ROLE_KEY", "").strip()
        if not supabase_url or not service_key:
            LOGGER.warning("Skipping social previews: selected Supabase credentials are unavailable")
            return None
        from supabase import create_client
        from backend.utils.log.shared_cleanup import current_run_lease_guard

        stats = refresh_social_previews(
            create_client(supabase_url, service_key),
            storage,
            lease_guard=current_run_lease_guard(),
        )
        LOGGER.info("Social preview refresh completed: %s", stats)
        return stats
    except Exception as error:
        from backend.utils.log.r2_budget import R2BudgetError, R2BudgetExceeded

        if isinstance(error, (R2BudgetError, R2BudgetExceeded)):
            raise
        LOGGER.warning("Social preview refresh was skipped after an error (%s)", type(error).__name__)
        return None


def main() -> None:
    from dotenv import load_dotenv

    load_dotenv(ROOT / ".env")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--target",
        choices=("development", "production"),
        default=os.environ.get("KARTISERET_TARGET"),
        help="Select the matching Supabase project and R2 bucket",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Upload missing cards and publish their database fingerprints",
    )
    parser.add_argument(
        "--allow-production",
        action="store_true",
        help="Explicitly permit database and R2 writes to production",
    )
    parser.add_argument(
        "--limit",
        type=int,
        help="Stop after processing this many missing or stale cards",
    )
    args = parser.parse_args()
    if not args.target:
        parser.error("select --target development or --target production")
    if args.limit is not None and args.limit < 1:
        parser.error("--limit must be a positive integer")

    selected = resolve_target_environment(args.target, os.environ)
    for key in PROFILE_KEYS:
        os.environ.pop(key, None)
    os.environ.update(selected)
    is_production = args.target == "production"
    if args.allow_production and not args.apply:
        parser.error("--allow-production requires --apply")
    if args.apply and is_production and not args.allow_production:
        parser.error("Production writes require the explicit --allow-production flag")

    from supabase import create_client

    storage = ArtworkStorage.from_environment()
    if storage is None:
        raise RuntimeError("The selected target has no complete R2 writer configuration")
    client = create_client(
        os.environ["SUPABASE_URL"], os.environ["SUPABASE_SERVICE_ROLE_KEY"]
    )
    result = refresh_social_previews(
        client, storage, dry_run=not args.apply, limit=args.limit,
    ) if not args.apply else None
    if args.apply:
        from backend.utils.log.shared_cleanup import lease_renewal_callback, maintenance_lease
        with maintenance_lease(skip_if_busy=False) as (store, token):
            result = refresh_social_previews(
                client, storage, dry_run=False, limit=args.limit,
                lease_guard=lease_renewal_callback(store, token),
            )
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
