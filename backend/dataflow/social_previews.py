"""Build and publish immutable Open Graph movie cards in the selected R2 bucket.

This module is called after catalog publication succeeds. Cards are rendered by
the site's existing Sharp renderer so generated bytes match the web design.
The database pointer is written last; a failed render/upload leaves the current
pointer untouched and the next ordinary scrape retries the item.
"""
